"""Generate the guest control sweep's table (caraxes/tools/ctlsweep.c) from controls.tsv.

The sweep issues, inside the guest, through the stock RM ioctl path, every control that
  - reaches GSP (route gsp in controls.tsv), so the device answers it;
  - a guest user-space process can call: privilege non-priv, or priv with --priv (the probe
    then runs as root; priv controls need an admin client);
  - is a getter by name (_GET, _QUERY, _IS_, _READ, _CHECK), so zeroed parameters change no
    state;
  - lives on an object the probe allocates without an engine: the client (RmClientResource),
    the device (Device), the subdevice (Subdevice), NV04_DISPLAY_COMMON (DispCommon),
    NV20_SUBDEVICE_DIAG (DiagApi), NV40_I2C (I2cApi) or GF100_ZBC_CLEAR (ZbcApi);
  - optionally, only the ids a coverage run left untouched (--only FILE: one id per line or
    the "untouched" lists of coverage-map.py --json).
Everything else is reported on stderr by reason (kernel-only, internal, setter, object the
probe cannot make). The output is a C header: {id, size, object, name}.
Usage: ctlsweep-gen.py [--priv] [--only FILE] [--controls TSV] > ctlsweep-table.h
"""
import argparse
import collections
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.join(os.path.dirname(HERE), "abi", "gsp-615.71.09", "controls.tsv")
OBJECTS = {"RmClientResource": "OBJ_CLIENT", "Device": "OBJ_DEVICE", "Subdevice": "OBJ_SUBDEVICE",
           "DispCommon": "OBJ_DISPCOMMON", "DiagApi": "OBJ_DIAG", "I2cApi": "OBJ_I2C", "ZbcApi": "OBJ_ZBC"}
GETTER = re.compile(r"_(GET|QUERY|IS|READ|CHECK)(_|$)")
MAX_SIZE = 65536


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--controls", default=DEFAULT)
    ap.add_argument("--priv", action="store_true")
    ap.add_argument("--only")
    a = ap.parse_args()
    only = None
    if a.only:
        text = open(a.only).read()
        try:
            j = json.loads(text)
            only = {int(x, 16) for v in j.get("untouched", {}).values() for x in v}
        except json.JSONDecodeError:
            only = {int(x, 0) for x in text.split()}
    rows, why = [], collections.Counter()
    header = None
    for line in open(a.controls):
        if line.startswith("#"):
            continue
        p = line.rstrip("\n").split("\t")
        if header is None:
            header = p
            continue
        r = dict(zip(header, p))
        cid = int(r["id"], 16)
        if r["route"] != "gsp":
            continue
        if only is not None and cid not in only:
            why["touched by the coverage run"] += 1
            continue
        priv = r["privilege"]
        if priv in ("internal", "kernel"):
            why[f"{priv}: only the guest kernel can send it (unit tests)"] += 1
            continue
        if priv == "priv" and not a.priv:
            why["priv: needs an admin client (--priv, run as root)"] += 1
            continue
        if not GETTER.search(r["name"]):
            why["not a getter by name (setters change state)"] += 1
            continue
        obj = OBJECTS.get(r["nvoc_class"])
        if obj is None:
            why[f"object {r['nvoc_class']} needs an engine or session the probe does not make"] += 1
            continue
        size = int(r["size"]) if r["size"].isdigit() else 0
        if size == 0 or size > MAX_SIZE:
            why["parameter size unknown or above 64 KiB"] += 1
            continue
        rows.append((cid, size, obj, r["name"], priv, r["provenance"]))
    print("// SPDX-License-Identifier: MIT")
    print(f"// Generated by caraxes/tools/ctlsweep-gen.py{' --priv' if a.priv else ''}"
          f"{' --only ' + os.path.basename(a.only) if a.only else ''} from {os.path.relpath(a.controls, os.path.dirname(os.path.dirname(HERE)))}; do not edit.")
    print(f"// {len(rows)} controls. Skipped: " + "; ".join(f"{k} {v}" for k, v in why.most_common()))
    print("static const struct sweep_entry SWEEP[] = {")
    for cid, size, obj, name, priv, prov in rows:
        print(f'    {{0x{cid:08x}u, {size}u, {obj}, "{name}", "{priv}", "{prov}"}},')
    print("};")
    for k, v in why.most_common():
        print(f"skipped {v}: {k}", file=sys.stderr)
    print(f"swept: {len(rows)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
