"""Extract the RTX 2070's own answers to chosen RM controls from the native control traces
(matrix/traces/<ver>/control/*.jsonl, ctrlout in/out pairs) into the TSV the device serves in
pure emulation (crates/vfio-user-nvgpu/src/recorded.rs, chips/<chip>/recorded-controls.tsv).

Usage: recorded-controls.py <trace dir> <cmd hex>... > recorded-controls.tsv
One line per distinct (cmd, request bytes): cmd, status, request hex, answer hex, source; a buffer
that ends in zeros is written <len>:<hex>. The committed table puts the lines of
caraxes/reference/rtx2070/kmd-controls-2026-09-26.tsv (same format) first: the first match wins."""
import glob, json, os, sys

def trim(h):
    """<len>:<hex> when the buffer ends in zero bytes (the device pads them back)."""
    t = h.rstrip("0")
    if len(t) % 2:
        t += "0"
    return h if len(t) == len(h) else f"{len(h) // 2}:{t}"


def main():
    tdir, cmds = sys.argv[1], {c.lower() for c in sys.argv[2:]}
    seen = {}
    for f in sorted(glob.glob(os.path.join(tdir, "*.jsonl"))):
        last = None
        with open(f, errors="replace") as fh:
            for n, line in enumerate(fh, 1):
                if '"ctrlout"' not in line:
                    continue
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                if r.get("cmd", "").lower() not in cmds:
                    continue
                if r["phase"] == "in":
                    last = r
                elif r["phase"] == "out" and last is not None and last["cmd"] == r["cmd"]:
                    key = (r["cmd"].lower(), last["dump"])
                    if key not in seen:
                        seen[key] = (r["status"], r["dump"], f"{os.path.basename(f)}:{n}")
                    last = None
    print("# SPDX-License-Identifier: MIT")
    print("# Generated by caraxes/tools/recorded-controls.py; do not edit.")
    print("# cmd\tstatus\trequest\tanswer\tsource (matrix/traces/610.57.04/control, RTX 2070, driver 610.57.04)")
    for (cmd, req), (st, out, src) in sorted(seen.items()):
        print(f"{cmd}\t{st}\t{trim(req)}\t{trim(out)}\t{src}")

if __name__ == "__main__":
    main()
