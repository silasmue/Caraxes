// Layout fingerprint of every RM API structure, control id and constant that
// the standalone query tools hard-code: caraxes/tools/host-facts.rs (facts),
// caraxes/tools/fifo-host-query.rs and caraxes/tools/lab-rm-query.rs. Those
// tools build with rustc alone and carry 610.57.04 layouts; they do not use
// crates/nvrm-sys. Compile this file against the SDK headers of another driver
// version and compare the output with the 610.57.04 output: identical output
// means the tools read the right bytes on that version.
//
//   caraxes/tools/lab-abi-check.sh [SDK_INCLUDE_DIR | VERSION]...
//
// One item per line on purpose: the wrapper turns a line that does not
// compile on an older or newer version into a "missing" line and retries,
// so the output names each item that is absent instead of failing whole.
//
// Include root: <open-gpu-kernel-modules>/src/common/sdk/nvidia/inc
// Nothing here touches a GPU; it only compiles and prints.
#include <stddef.h>
#include <stdio.h>
#include "nvtypes.h"
