    S(NV2080_CTRL_GPU_GET_NAME_STRING_PARAMS);
    C(NV2080_CTRL_CMD_GPU_GET_SHORT_NAME_STRING);
    S(NV2080_CTRL_GPU_GET_SHORT_NAME_STRING_PARAMS);
