    O(NV2080_CTRL_CMD_FB_GET_FB_REGION_FB_REGION_INFO, bProtected);
    O(NV2080_CTRL_CMD_FB_GET_FB_REGION_FB_REGION_INFO, regionTag);
    C(NV2080_CTRL_CMD_GR_GET_GPC_MASK);
    S(NV2080_CTRL_GR_GET_GPC_MASK_PARAMS);
