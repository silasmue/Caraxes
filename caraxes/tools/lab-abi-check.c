    S(NV2080_CTRL_GR_GET_GFX_GPC_AND_TPC_INFO_PARAMS);
    O(NV2080_CTRL_GR_GET_GFX_GPC_AND_TPC_INFO_PARAMS, physGfxGpcMask);
