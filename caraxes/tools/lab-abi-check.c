    C(NV2080_CTRL_FB_INFO_INDEX_TOTAL_RAM_SIZE);
    C(NV2080_CTRL_FB_INFO_INDEX_HEAP_SIZE);
    C(NV2080_CTRL_FB_INFO_INDEX_MAPPABLE_HEAP_SIZE);
    C(NV2080_CTRL_FB_INFO_INDEX_FB_TAX_SIZE_KB);
    C(NV2080_CTRL_FB_INFO_INDEX_HEAP_BASE_KB);
    C(NV2080_CTRL_FB_INFO_INDEX_LARGEST_FREE_REGION_SIZE_KB);
    C(NV2080_CTRL_FB_INFO_INDEX_LARGEST_FREE_REGION_BASE_KB);
    C(NV2080_CTRL_FB_INFO_INDEX_HEAP_FREE);
    C(NV2080_CTRL_FB_INFO_INDEX_BAR1_AVAIL_SIZE);
    C(NV2080_CTRL_FB_INFO_INDEX_HEAP_START);
    C(NV2080_CTRL_FB_INFO_INDEX_BAR1_MAX_CONTIGUOUS_AVAIL_SIZE);
    C(NV2080_CTRL_FB_INFO_INDEX_USABLE_RAM_SIZE);
    C(NV2080_CTRL_FB_INFO_INDEX_HEAP_OFFLINE_SIZE);
    C(NV2080_CTRL_FB_INFO_INDEX_SUSPEND_RESUME_RSVD_SIZE);
